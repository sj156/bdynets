preparation_session(base)
library(bdynets)
source(file.path(base,'prepare.R'))
reject<-function(expr)stopifnot(inherits(try(force(expr),silent=TRUE),'try-error'))
native<-read_metropolis_lesson(file.path(base,'data/lesson'))
x<-metropolis_input(native)
stopifnot(x$flow$flow[1]==4.67,x$measurements$value[1]==81.88,x$measurements$value[5]==.040)
bad<-native;bad$labels[2]<-bad$labels[1];reject(metropolis_input(bad))
bad<-native;bad$labels[2]<-'2024-10-18 00:05:47';reject(metropolis_input(bad))
# One supplied road is a valid matrix boundary, with the same source method.
coverage<-metropolis_bins(native$volume[1,,drop=FALSE],native$labels)
stopifnot(identical(dim(coverage$values),c(1L,2L)))
full<-metropolis_input(readRDS(file.path(base,'data/source.rds')))
stopifnot(sum(full$provenance$native_coverage$speed$frame_imputed)==5466L,
 sum(full$provenance$native_coverage$speed$native_status==as.raw(0))==16964L)
gold<-readRDS(file.path(base,'data/input.rds'))
for(key in c('roads','flow','events','nodes','od','measurements','times','time_labels','interval_seconds','unit','timezone'))
 stopifnot(identical(full[[key]],gold[[key]]))
if(!is.null(gold$trends))stopifnot(identical(full$trends$value,gold$trends$value))
source_files<-list.files(file.path(base,'data'),full.names=TRUE,recursive=TRUE)
before<-tools::md5sum(source_files)
