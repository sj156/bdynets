od_fixture <- function() list(
  nodes=data.frame(node_id=c('a','b'),longitude=factor(c('12','12.1')),latitude=factor(c('51','51.1'))),
  flows=data.frame(origin_id=c('a','a'),destination_id=c('b','b'),flow=factor(c('10','20'))))
test_that('OD boundary parses factor values and accepts minimal defaults', {
  z<-od_fixture()
  a<-aggregate_od_data(z$nodes,z$flows,1)
  expect_equal(sum(a$flows$flow),30)
  expect_equal(a$nodes$longitude,c(12,12.1))
  m<-traffic_od_map(z$nodes,z$flows,basemap=NULL,draw=FALSE)
  expect_equal(m$summary$selected_flow,30)
  expect_equal(traffic_od_map(a,basemap=NULL,draw=FALSE)$summary$selected_flow,30)
  expect_error(traffic_od_map(a,basemap=NULL,draw=FALSE,hour_window=c(1,2)),'time column')
})
test_that('canonical OD object validates mappings counts units IDs and CRS', {
  z<-od_fixture();names(z$nodes)<-c('station','x','y');names(z$flows)<-c('from','to','n')
  x<-traffic_od_data(z$nodes,z$flows,node_columns=c(node_id='station',lon='x',lat='y'),flow_columns=c(origin_id='from',destination_id='to',flow='n'))
  expect_s3_class(x,'traffic_od_data');expect_equal(x$unit,'trips')
  expect_equal(plot(x,basemap=NULL,draw=FALSE)$summary$selected_flow,30)
  z<-od_fixture();z$flows$flow<-c(1.5,2)
  expect_error(traffic_od_data(z$nodes,z$flows),'integers')
  z<-od_fixture();z$flows$origin_id[1]<-'unknown'
  expect_error(traffic_od_data(z$nodes,z$flows),'endpoint')
  expect_error(traffic_od_data(z$nodes,z$flows,crs='EPSG:3857'),'CRS')
  z<-od_fixture();z$nodes$longitude[1]<-NA
  expect_error(traffic_od_data(z$nodes,z$flows),'finite')
})
test_that('road and event mappings share strict numeric normalization and coverage', {
  roads<-data.frame(link='r');roads$shape<-list(rbind(c(12,51),c(12.1,51.1)))
  f<-data.frame(link='r',clock=1,amount=factor('20'))
  e<-data.frame(clock=1,x=factor('12'),y=factor('51'))
  x<-traffic_data(roads,f,e,unit='vehicles/hour',road_columns=c(road_id='link',geometry='shape'),flow_columns=c(road_id='link',time='clock',flow='amount'),event_columns=c(time='clock',lon='x',lat='y'))
  expect_equal(x$values[1,1],20);expect_equal(x$events$lon,12);expect_equal(x$unit,'vehicles/hour')
  expect_equal(traffic_coverage(x),data.frame(roads=1L,frames=1L,road_time_cells=1L,observed=1L,missing=0L,zero=0L,event_starts=1L))
  f$amount<-'bad'
  expect_error(traffic_data(roads,f,e,road_columns=c(road_id='link',geometry='shape'),flow_columns=c(road_id='link',time='clock',flow='amount'),event_columns=c(time='clock',lon='x',lat='y')),'numeric')
})
