test_that('OD event composition renders selected events in the frozen viewport', {
 frozen_usr<-NULL
 local_mocked_bindings(.tm_static_context=function(base,limits){frozen_usr<<-limits},.package='bdynets')
 z<-od_fixture();z$flows$time<-c('2026-01-01 01:00:00','2026-01-01 02:00:00')
 e<-data.frame(when=c('2026-01-01 01:30:00','2026-01-01 02:30:00'),x=factor(c('12.05','12.06')),y=factor(c('51.05','51.06')))
 p<-tempfile(fileext='.png');q<-tempfile(fileext='.png');r<-tempfile(fileext='.png')
 a<-traffic_od_map(z$nodes,z$flows,basemap=NULL,draw=FALSE,output_file=p)
 b<-bdynets:::.tm_od_map_reference(transform(z$nodes,longitude=c(12,12.1),latitude=c(51,51.1)),transform(z$flows,flow=c(10,20)),node_columns=c(id='node_id',longitude='longitude',latitude='latitude'),basemap=NULL,draw=FALSE,output_file=q)
 expect_identical(unname(tools::md5sum(p)),unname(tools::md5sum(q)))
 m<-traffic_od_map(z$nodes,z$flows,basemap=NULL,draw=FALSE,output_file=r,events=e,event_columns=c(time='when',lon='x',lat='y'),hour_window=c(1,2))
 expect_equal(nrow(m$event_overlay$events),1)
 expect_equal(m$event_overlay$projected,bdynets:::.tm_project(matrix(c(12.05,51.05),ncol=2)))
 expect_equal(length(m$event_overlay$viewport),4)
 expect_identical(m$event_overlay$viewport,frozen_usr)
 expect_true(file.info(r)$size>1000)
 traffic_od_map(z$nodes,z$flows,basemap=NULL,draw=FALSE,output_file=q,hour_window=c(1,2))
 expect_false(identical(unname(tools::md5sum(q)),unname(tools::md5sum(r))))
 expect_equal(m$summary$selected_flow,10)
 unlink(c(p,q,r))
})

