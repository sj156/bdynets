if(nzchar(Sys.getenv('TRAFFICMAP_SOURCE'))) {
 source(Sys.getenv('TRAFFICMAP_SOURCE'));options(trafficmap.assets=normalizePath('inst/package_assets'))
} else library(bdynets)
r<-data.frame(road_id=c('a','b'),region=c('West','East'))
r$geometry<-list(rbind(c(10,50),c(10.01,50)),rbind(c(11,50),c(11.01,50)))
f<-data.frame(road_id=rep(c('a','b'),2),time=rep(c(0,3600),each=2),flow=c(10,NA,20,30))
e<-data.frame(time=c(0,3600),lon=c(10,11),lat=50,region=c('West','East'))
x<-traffic_data(r,f,e,interval_seconds=3600)
p<-tempfile(fileext='.html')
traffic_report(x,p)
s<-paste(readLines(p,warn=FALSE),collapse='\n')
stopifnot(!grepl('window.trafficMap|leaflet|Interactive map|DecompressionStream',s,ignore.case=TRUE))
stopifnot(grepl('Whole-period coverage',s,fixed=TRUE),grepl('Selected interval',s,fixed=TRUE))
traffic_report(x,p,index=2L,region='East')
s<-paste(readLines(p,warn=FALSE),collapse='\n')
stopifnot(grepl('East',s,fixed=TRUE),grepl(x$time_labels[2],s,fixed=TRUE),grepl('data:image/png;base64,',s,fixed=TRUE))
stopifnot(inherits(tryCatch(traffic_report(x,p,index=0),error=identity),'error'))
stopifnot(inherits(tryCatch(traffic_report(x,p,region='Unknown'),error=identity),'error'))
unlink(p)
cat('Static report, whole-period versus selected-time scope, region/time arguments and invalid selections passed.\n')
