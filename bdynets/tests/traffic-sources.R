options(bdynets.basemap.auto=FALSE)
library(bdynets)
stopifnot(exists('extract_traffic_data',mode='function'))
fail<-function(e)inherits(tryCatch(force(e),error=identity),'error')
out<-tempfile('source-test-');dir.create(out)
text<-'const payload = {\n "segments":[{"id":"a"}],\n "frames":[{"time":0,"volume":[1],"speed":[2],"congestion":[0.3]}]\n};'
writeLines(text,file.path(out,'saved.js'));js<-extract_traffic_data(file.path(out,'saved.js'),assignment='payload',file=file.path(out,'source.rds'))
stopifnot(js$payload$frames[[1]]$congestion[[1]]==.3,identical(extract_traffic_data(file.path(out,'source.rds'))$payload,js$payload))
writeLines(jsonlite::toJSON(js$payload,auto_unbox=TRUE),gzfile(file.path(out,'source.json.gz')))
a<-extract_traffic_data(file.path(out,'source.json.gz'));stopifnot(isTRUE(all.equal(a$payload,js$payload,check.attributes=FALSE)))
writeLines(paste0('<html><script>',text,'</script></html>'),file.path(out,'saved.html'));stopifnot(identical(extract_traffic_data(file.path(out,'saved.html'),assignment='payload')$payload,js$payload))
writeLines('const payload = system("unexpected");',file.path(out,'bad.js'));stopifnot(fail(extract_traffic_data(file.path(out,'bad.js'),assignment='payload')),fail(extract_traffic_data(file.path(out,'saved.js'))),fail(extract_traffic_data(file.path(out,'saved.js'),assignment='payload',file=file.path(out,'source.rds'))))
writeLines(paste(text,text,sep='\n'),file.path(out,'double.js'));stopifnot(fail(extract_traffic_data(file.path(out,'double.js'),assignment='payload')))
write.csv(data.frame(station=c('a','b'),amount=c(1,2)),gzfile(file.path(out,'table.csv.gz')),row.names=FALSE);stopifnot(sum(extract_traffic_data(file.path(out,'table.csv.gz'))$payload$amount)==3)
unlink(out,recursive=TRUE);cat('Source extraction: multiline literals, HTML, RDS, JSON.GZ, CSV.GZ, preservation, identities and invalid/ambiguous inputs passed.\n')

nullfile<-tempfile(fileext=".js");writeLines("const payload = null;",nullfile)
stopifnot(is.null(extract_traffic_data(nullfile,assignment="payload")$payload));unlink(nullfile)

largefile<-tempfile(fileext=".js")
large<-list(note=strrep("x",1100000),values=list(1,2))
writeLines(paste0("window.payload = ",jsonlite::toJSON(large,auto_unbox=TRUE),";"),largefile)
stopifnot(isTRUE(all.equal(extract_traffic_data(largefile,assignment="window.payload")$payload,large,check.attributes=FALSE)));unlink(largefile)
commentfile<-tempfile(fileext='.js')
writeLines('/*\nconst payload = {"wrong": true};\n*/\nconst payload =\n {"right": true};',commentfile)
stopifnot(identical(extract_traffic_data(commentfile,assignment='payload')$payload,list(right=TRUE)))
writeLines('const note = `\nconst payload = {"wrong":true};\n`;\n// payload = {"wrong": true};\nconst payload = "source string";',commentfile)
stopifnot(identical(extract_traffic_data(commentfile,assignment='payload')$payload,'source string'));unlink(commentfile)

htmlfile<-tempfile(fileext='.html')
writeLines('<html><!-- <script>const payload = {"wrong":true};</script> --><script>const payload = {"note":"<!-- source text -->","x":1};</script></html>',htmlfile)
stopifnot(identical(extract_traffic_data(htmlfile,assignment='payload')$payload$note,'<!-- source text -->'));unlink(htmlfile)

